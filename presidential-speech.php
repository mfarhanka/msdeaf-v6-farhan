          berperanan mengurus dan melaksanakan semua program dan aktiviti kesukanan untuk warga Pekak negara.
        </p>
        <p>
          Sebagai Sebuah Badan NGO Sukan Berprestasi Tinggi, MSDeaf sentiasa peka dan memainkan peranan utama
          melaksana berbagai program dan aktiviti kesukanan untuk warga Pekak negara di peringkat kebangsaan dan
          antarabangsa seperti Sukan Orang Pekak Asean, Sukan Orang Pekak Asia-Pasifik Dan Sukan Deaflympics. Oleh
          kerana itu MSDeaf amat memerlukan sokongan dari semua pihak.
        </p>
        <p>
          Usaha MSDeaf ini turut disokong oleh Kementerian Belia dan Sukan Malaysia yang telah mengiktirafkan
          sukan warga Pekak dengan memasukkan agenda sukan warga Pekak dalam Akta Pembangunan Sukan (Pindaan)
          2018 (Akta 576) yang menyatakan bahawa badan sukan warga Pekak Malaysia diiktirafkan sebagai badan sukan
          warga Pekak yang diberi mandat dan kepercayaan melaksanakan program kesukanan warga Pekak peringkat
          kebangsaan dan penyertaan warga Pekak Malaysia hingga ke peringkat antarabangsa.
        </p>
        <p>
          Usaha-usaha bagi memartabatkan sukan warga Pekak negara ini juga turut di bantu oleh lain-lain agensi
          kerajaan seperti Jabatan Belia Dan Sukan Negara (JBSN), Institut Sukan Negara (ISN), Majlis Sukan Negara
          Malaysia (MSNM). Selain dari bantuan teknikal dan kepakaran dari badan jenis sukan kebangsaan seperti
          Persatuan Bolasepak Malaysia (FAM), Persatuan Badminton Malaysia (BAM), Kesatuan Olahraga Amatur Malaysia
          (KOAM) Kongres Tenpin Boling Malaysia (MTBC) dan lain-lain lagi badan sukan kebangsaan.
        </p>
        <p>
          Hasrat dan impian MSDeaf, masyarakat marhaen dapat memberi sokongan dalam usaha memperkasakan sukan
          warga Pekak di Malaysia kerana kami adalah sebuah NGO sukan yang bergantung sepenuhnya dari sokongan
          dan bantuan semua pihak bagi melaksanakan semua aktiviti kesukanan membabitkan sukan warga Pekak
          kebangsaan dan antarabangsa.
        </p>
